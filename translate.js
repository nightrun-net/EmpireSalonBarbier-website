/* =====================================================
   TRANSLATION ENGINE
   ===================================================== */

const translateOriginals = new WeakMap();

let currentLanguage = "fr";

function tr(frenchText) {

    if (currentLanguage === "fr") {
        return frenchText;
    }

    const key = String(frenchText).trim();

    const direct = TRANSLATIONS[key]?.[currentLanguage];

    if (direct) {
        return direct;
    }

    // Service labels can include a price.
    const match = key.match(
        /^(.*?)\s*(—\s*\d+\s*frs)$/
    );

    if (match) {

        const service = match[1].trim();

        const translatedService =
            TRANSLATIONS[service]?.[currentLanguage] ||
            service;

        return translatedService + " " + match[2];
    }

    return frenchText;
}


/* =====================================================
   TRANSLATE TEXT NODES
   ===================================================== */

function translateNode(node) {

    const parent = node.parentElement;

    if (
        !parent ||
        ["SCRIPT", "STYLE", "NOSCRIPT"].includes(parent.tagName)
    ) {
        return;
    }

    const original =
        translateOriginals.get(node) ?? node.nodeValue;

    if (!original.trim()) {
        return;
    }

    if (!translateOriginals.has(node)) {
        translateOriginals.set(node, original);
    }

    const leading = original.match(/^\s*/)[0];
    const trailing = original.match(/\s*$/)[0];

    const output =
        leading + tr(original.trim()) + trailing;

    if (node.nodeValue !== output) {
        node.nodeValue = output;
    }
}


/* =====================================================
   TRANSLATE THE WEBSITE
   ===================================================== */

function translatePage(root = document.body) {

    if (!root) return;

    const walker = document.createTreeWalker(
        root,
        NodeFilter.SHOW_TEXT
    );

    let node;

    while ((node = walker.nextNode())) {
        translateNode(node);
    }

    // Translate input placeholders.
    const elements = root.querySelectorAll(
        "input[placeholder], textarea[placeholder]"
    );

    elements.forEach(el => {

        if (!el.dataset.originalPlaceholder) {
            el.dataset.originalPlaceholder = el.placeholder;
        }

        el.placeholder = tr(
            el.dataset.originalPlaceholder
        );

    });

    document.documentElement.lang = currentLanguage;

    const languageSelect =
        document.getElementById("language");

    if (languageSelect) {
        languageSelect.value = currentLanguage;
    }

    // Update calendar month in the selected language.
    if (
        typeof currentMonth !== "undefined" &&
        typeof currentYear !== "undefined"
    ) {

        const month =
            document.getElementById("calendarMonth");

        if (month) {

            const locale =
                currentLanguage === "fr" ? "fr-FR" :
                currentLanguage === "de" ? "de-DE" :
                "en-GB";

            month.textContent =
                new Intl.DateTimeFormat(locale, {
                    month: "long",
                    year: "numeric"
                }).format(
                    new Date(currentYear, currentMonth, 1)
                );
        }
    }
}


/* =====================================================
   SWITCH LANGUAGE WITHOUT RELOADING
   ===================================================== */

function switchLanguage() {

    const code =
        document.getElementById("language").value;

    if (!["fr", "en", "de"].includes(code)) {
        return;
    }

    currentLanguage = code;

    localStorage.setItem(
        "empireSalonLanguage",
        code
    );

    translatePage();
}


/* =====================================================
   INITIALIZE
   ===================================================== */

document.addEventListener("DOMContentLoaded", () => {

    const stored = localStorage.getItem(
        "empireSalonLanguage"
    );

    currentLanguage =
        ["fr", "en", "de"].includes(stored)
            ? stored
            : "fr";

    translatePage();

    const observer = new MutationObserver(mutations => {

        for (const mutation of mutations) {

            for (const node of mutation.addedNodes) {

                // Ignore text-only updates.
                if (node.nodeType !== Node.ELEMENT_NODE) {
                    continue;
                }

                // Avoid processing scripts or styles.
                if (["SCRIPT", "STYLE"].includes(node.tagName)) {
                    continue;
                }

                // Translate only newly added HTML elements.
                translatePage(node);
            }
        }
    });

    observer.observe(document.body, {
        childList: true,
        subtree: true
    });

    observer.observe(document.body, {
        childList: true,
        subtree: true
    });

});
